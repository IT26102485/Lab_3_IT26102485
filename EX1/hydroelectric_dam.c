#include <stdio.h>

int main(void)
{
    const double GRAVITY = 9.8;
    const double EFFICIENCY = 0.9;
    const double WATER_DENSITY = 1000.0;

    double height,flow_rate;
    double mass_per_second;
    double power_watts, power_megawatts;

    printf("Enter height of the dam(meter): ");
    scanf("%lf", &height);

    printf("Enter flow rate of water(cubic meters per second): ");
    scanf("%lf", &flow_rate);

    mass_per_second = flow_rate * WATER_DENSITY;
    power_watts = EFFICIENCY * mass_per_second * GRAVITY * height;
    power_megawatts = power_watts / 1000000.0;

    printf("Predicted power generated by the hydroelectric dam: %.2f megawatts\n", power_megawatts);

    return 0;
}

    




    
